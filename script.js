function handleFormSubmit(event) {
    event.preventDefault();

    const contactForm = event.target;
    const name = contactForm.querySelector('#name').value.trim();
    const email = contactForm.querySelector('#email').value.trim();
    const message = contactForm.querySelector('#message').value.trim();
    const submitButton = contactForm.querySelector('button[type="submit"]');

    if (name.length < 2) {
        alert(translations[currentLang].alert_invalid_name);
        return;
    }

    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(email)) {
        alert(translations[currentLang].alert_invalid_email);
        return;
    }

    if (message.length < 15) {
        alert(translations[currentLang].alert_message_short);
        return;
    }

    const originalButtonText = submitButton.innerHTML;
    submitButton.innerHTML = translations[currentLang].form_sending;
    submitButton.disabled = true;
    
    const serviceID = 'service_9wtp4ng';
    const templateID = 'template_utwrxar';
    const publicKey = '4h8jCPoav3R_0Om1p';

    const templateParams = {
        name: name,
        email: email,
        message: message,
    };

    emailjs.send(serviceID, templateID, templateParams, publicKey)
        .then(response => {
           console.log('E-posta başarıyla gönderildi!', response.status, response.text);
           alert(translations[currentLang].alert_email_success);
           submitButton.innerHTML = translations[currentLang].form_sent;
           contactForm.reset();
           setTimeout(() => {
                submitButton.innerHTML = originalButtonText;
                submitButton.disabled = false;
           }, 3000);
        }, err => {
           console.error('E-posta gönderilirken hata oluştu:', err);
           alert(translations[currentLang].alert_email_error);
           submitButton.innerHTML = translations[currentLang].form_error;
           setTimeout(() => {
                submitButton.innerHTML = originalButtonText;
                submitButton.disabled = false;
           }, 3000);
        });
}

