let currentLang = 'tr'; 

const setLanguage = (lang) => {
    currentLang = lang;
    document.querySelectorAll('[data-translate]').forEach(el => {
        const key = el.getAttribute('data-translate');
        if (translations[lang] && translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    document.querySelectorAll('[data-translate-placeholder]').forEach(el => {
        const key = el.getAttribute('data-translate-placeholder');
        if (translations[lang] && translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    const langTrButton = document.getElementById('lang-tr');
    const langEnButton = document.getElementById('lang-en');
    if (lang === 'tr') {
        langTrButton.classList.add('active');
        langEnButton.classList.remove('active');
        document.documentElement.lang = 'tr';
    } else {
        langEnButton.classList.add('active');
        langTrButton.classList.remove('active');
        document.documentElement.lang = 'en';
    }
    localStorage.setItem('language', lang);
    
    const titleElement = document.getElementById('dynamic-title');
    if (titleElement) {
        titleElement.textContent = translations[lang].dynamic_title_initial;
    }
};

window.selectLanguage = (lang) => {
    const languageModal = document.getElementById('language-modal-overlay');
    setLanguage(lang);
    languageModal.classList.add('hidden');
};

document.addEventListener('DOMContentLoaded', () => {
    const languageModal = document.getElementById('language-modal-overlay');
    const langTrButton = document.getElementById('lang-tr');
    const langEnButton = document.getElementById('lang-en');
    
    langTrButton.addEventListener('click', () => setLanguage('tr'));
    langEnButton.addEventListener('click', () => setLanguage('en'));
    
    const savedLang = localStorage.getItem('language');
    if (savedLang) {
        languageModal.classList.add('hidden');
        setLanguage(savedLang);
    } else {
        languageModal.classList.remove('hidden');
    }
});


