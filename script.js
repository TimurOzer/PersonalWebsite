window.addEventListener('load', () => {
    const headingElement = document.getElementById('animated-heading');
    const titleElement = document.getElementById('dynamic-title');
    
    let hasAnimationPlayed = false;

    const deletingSpeed = 100;
    const typingSpeed = 150;

    function typeEffect() {
        const initialTitle = translations[currentLang].dynamic_title_initial;
        const finalTitle = translations[currentLang].dynamic_title_final;
        let charIndex = initialTitle.length;
        let isDeleting = true;

        function animate() {
            if (isDeleting) {
                charIndex--;
                titleElement.textContent = initialTitle.substring(0, charIndex);

                if (charIndex === 0) {
                    isDeleting = false;
                    titleElement.classList.remove('deleting');
                    setTimeout(animate, 500);
                    return;
                }
            } else {
                charIndex++;
                titleElement.textContent = finalTitle.substring(0, charIndex);

                if (charIndex === finalTitle.length) {
                    document.querySelector('.cursor').style.display = 'none';
                    return;
                }
            }
            
            const speed = isDeleting ? deletingSpeed : typingSpeed;
            setTimeout(animate, speed);
        }

        titleElement.classList.add('deleting');
        setTimeout(animate, 1000);
    }

    const titleObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting && !hasAnimationPlayed) {
                hasAnimationPlayed = true;
                
                setTimeout(() => {
                    typeEffect();
                }, 750);

                titleObserver.unobserve(entry.target);
            }
        });
    }, {
        threshold: 0.5
    });

    if (headingElement) {
        titleObserver.observe(headingElement);
    }
});

document.addEventListener('DOMContentLoaded', () => {
    const lightbox = document.getElementById('lightbox');
    if (!lightbox) return;
    
    const lightboxImg = document.getElementById('lightbox-img');
    const galleryItems = document.querySelectorAll('.gallery-item');
    const closeBtn = document.querySelector('.lightbox-close');

    galleryItems.forEach(item => {
        item.addEventListener('click', e => {
            e.preventDefault();
            const imgSrc = item.querySelector('img').src;
            lightboxImg.src = imgSrc;
            lightbox.classList.remove('lightbox-hidden');
            lightbox.classList.add('lightbox-visible');
        });
    });

    const closeLightbox = () => {
        lightbox.classList.add('lightbox-hidden');
        lightbox.classList.remove('lightbox-visible');
    }

    if(closeBtn) {
        closeBtn.addEventListener('click', closeLightbox);
    }

    lightbox.addEventListener('click', e => {
        if (e.target === lightbox) {
            closeLightbox();
        }
    });
});

